import json, sys, pathlib
kb = pathlib.Path(sys.argv[1]); out = pathlib.Path(sys.argv[2])
DOCS = {
 "p17": ("документы компании__Договор поставки П-17-2024 Альфа-Трейд.txt", "Договор", "Договор поставки (ООО «Альфа-Трейд»)", "П-17/2024", "12.02.2024"),
 "ds1": ("документы компании__Доп соглашение 1 к договору П-17-2024.txt", "Доп. соглашение", "Дополнительное соглашение к договору П-17/2024", "1", "03.09.2024"),
 "reg2025": ("документы компании__Регламент согласования договоров ред 2025.txt", "Регламент", "Регламент согласования договоров (ред. 2025)", "14-П", "01.03.2025"),
}
docs, texts = {}, {}
for k, (fn, typ, title, num, date) in DOCS.items():
    t = (kb / fn).read_text(encoding="utf-8").strip()
    texts[k] = t
    docs[k] = {"doc_id": k, "type": typ, "title": title, "number": num, "date": date, "text": t}
def line(k, prefix):
    for ln in texts[k].splitlines():
        if ln.strip().startswith(prefix): return ln.strip()
    raise SystemExit(f"not found {k} {prefix}")
def src(i, k, p):
    d = docs[k]
    return {"id": i, "doc_id": k, "type": d["type"], "title": d["title"], "number": d["number"], "date": d["date"],
            "pinpoint": "п. " + p.strip("«").rstrip("."), "fragment": line(k, p)}
